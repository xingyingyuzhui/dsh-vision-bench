// @ts-check

const IDENTIFIER_RE = /^[a-zA-Z_][a-zA-Z0-9_.]*$/

/**
 * Validates that an identifier contains only safe alphanumeric characters and dots,
 * preventing arbitrary script injection into Keil debugger.
 *
 * @param {string} ident
 * @param {string} [context]
 */
export function validateScriptIdentifier(ident, context = 'identifier') {
  if (!ident || typeof ident !== 'string' || !IDENTIFIER_RE.test(ident)) {
    throw new Error(`非法的脚本标识符 [${context}]: "${ident}" (只允许字母、数字、下划线与点号)`)
  }
}

/**
 * Builds a safe Keil debugger Signal Function script from a structured scenario.
 *
 * @param {{
 *   name: string,
 *   signals: Array<{
 *     target: string,
 *     kind?: 'set' | 'ramp' | 'step' | 'pulse',
 *     delaySeconds?: number,
 *     initialValue?: number,
 *     targetValue?: number,
 *     steps?: number,
 *     stepDelaySeconds?: number,
 *   }>,
 *   repeatCount?: number,
 * }} scenario
 * @returns {string} Safe Keil C-script signal function definition
 */
export function buildSignalFunctionScript(scenario) {
  if (!scenario || typeof scenario !== 'object') {
    throw new Error('需要有效的 scenario 配置对象')
  }

  const fnName = scenario.name || 'VisionSimScenario'
  validateScriptIdentifier(fnName, 'scenario.name')

  const lines = []
  lines.push('// Generated by Vision Keil Simulator Bridge')
  lines.push(`// Scenario: ${fnName}`)
  lines.push(`signal void ${fnName}(void) {`)

  const repeat = Math.max(1, Math.min(1000, Number(scenario.repeatCount) || 1))
  if (repeat > 1) {
    lines.push('  int _iter;')
    lines.push(`  for (_iter = 0; _iter < ${repeat}; _iter++) {`)
  }

  const indent = repeat > 1 ? '    ' : '  '

  for (const sig of scenario.signals || []) {
    validateScriptIdentifier(sig.target, 'signal.target')
    const target = sig.target
    const kind = sig.kind || 'set'

    if (sig.delaySeconds && Number(sig.delaySeconds) > 0) {
      const sec = Number(sig.delaySeconds).toFixed(4)
      lines.push(`${indent}swatch(${sec});`)
    }

    if (kind === 'set') {
      const val = Number(sig.targetValue ?? sig.initialValue ?? 0)
      if (!Number.isFinite(val)) throw new Error(`非法的数值: ${val}`)
      lines.push(`${indent}${target} = ${val};`)
    } else if (kind === 'pulse') {
      const initVal = Number(sig.initialValue ?? 0)
      const pulseVal = Number(sig.targetValue ?? 1)
      const pulseSec = Number(sig.stepDelaySeconds || 0.01).toFixed(4)
      lines.push(`${indent}${target} = ${pulseVal};`)
      lines.push(`${indent}swatch(${pulseSec});`)
      lines.push(`${indent}${target} = ${initVal};`)
    } else if (kind === 'ramp') {
      const startVal = Number(sig.initialValue ?? 0)
      const endVal = Number(sig.targetValue ?? 100)
      const steps = Math.max(2, Math.min(100, Number(sig.steps) || 10))
      const stepDelay = Number(sig.stepDelaySeconds || 0.01).toFixed(4)
      const stepDelta = (endVal - startVal) / steps

      lines.push(`${indent}// Ramp ${target} from ${startVal} to ${endVal} in ${steps} steps`)
      for (let s = 0; s <= steps; s++) {
        const curVal = (startVal + stepDelta * s).toFixed(4)
        lines.push(`${indent}${target} = ${curVal};`)
        if (s < steps) {
          lines.push(`${indent}swatch(${stepDelay});`)
        }
      }
    }
  }

  if (repeat > 1) {
    lines.push('  }')
  }

  lines.push('}')
  lines.push('')

  return lines.join('\n')
}

/**
 * Generates initialization script (.ini) for loading symbols and vector table.
 *
 * @param {{
 *   vtorAddress?: string | number,
 *   loadApplication?: boolean,
 *   signalScripts?: string[],
 * }} [options]
 * @returns {string}
 */
export function buildDebugInitScript(options = {}) {
  const lines = []
  lines.push('// Generated by Vision Keil Debug Init Builder')
  lines.push('RESET')

  if (options.vtorAddress != null) {
    const vtor =
      typeof options.vtorAddress === 'number'
        ? `0x${options.vtorAddress.toString(16).toUpperCase()}`
        : String(options.vtorAddress)
    lines.push(`_WDWORD(0xE000ED08, ${vtor}); // VTOR`)
  }

  if (Array.isArray(options.signalScripts)) {
    for (const script of options.signalScripts) {
      lines.push(script)
    }
  }

  return lines.join('\n')
}
