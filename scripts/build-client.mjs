import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

function stripModule(src) {
  return src
    .replace(/^import[\s\S]*?from '[^']+'\n+/gm, '')
    .replace(/^export /gm, '')
}

function assertUniqueBindings(stripped, file) {
  const re = /^(?:async\s+)?(?:function\*?|class|const|let|var)\s+([A-Za-z_$][\w$]*)/gm
  let match
  while ((match = re.exec(stripped))) {
    const name = match[1]
    const prev = seen.get(name)
    if (prev) {
      throw new Error('duplicate binding "' + name + '" in ' + file + ' (already in ' + prev + '); strip-concat is one factory scope')
    }
    seen.set(name, file)
  }
}

const seen = new Map()

const parts = [
  'bench-i18n.mjs',
  'bench-styles.mjs',
  'bench-settings.mjs',
  'bench-points.mjs',
  'bench-devices.mjs',
  'bench-shared.mjs',
  'bench-view.mjs',
  'bench-hmi.mjs',
  'bench-live.mjs',
  'bench-map.mjs',
  'bench-overview.mjs',
  'bench-runtime.mjs',
].map((file) => {
  const stripped = stripModule(readFileSync(join(root, file), 'utf8'))
  assertUniqueBindings(stripped, file)
  return stripped
})

const banner = `// Generated by scripts/build-client.mjs. Do not edit by hand.

`
const body = `window.__ModuleLoader__.load({
  id: 'dsh-vision-bench',
  factory: (require) => {
    var module = { exports: {} }
    var exports = module.exports

    var name = 'dsh-vision-bench'
    var inject = ['slots']

${parts.join('\n')}

    exports.name = name
    exports.inject = inject
    exports.apply = apply
    return module.exports
  },
})
`

const next = banner + body
const dest = join(root, 'client.js')
const check = process.argv.includes('--check')
if (check) {
  const current = readFileSync(dest, 'utf8')
  if (current !== next) {
    console.error('client.js is stale; run node scripts/build-client.mjs')
    process.exit(1)
  }
  process.exit(0)
}
writeFileSync(dest, next)
