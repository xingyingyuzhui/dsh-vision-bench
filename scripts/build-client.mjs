import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { Virtualizer } from '@tanstack/virtual-core'
import * as esbuild from 'esbuild'
import { assertClientBudget, normalizeNewlines, sha256Text } from './check-client-budget.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const REACT_DOM_SHIM = join(root, 'scripts/react-dom-shim.mjs')
const BANNER = `// Generated by scripts/build-client.mjs. Do not edit by hand.

`

const ESBUILD_COMMON = {
  absWorkingDir: root,
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['es2020'],
  write: false,
  minify: true,
  legalComments: 'none',
  sourcemap: false,
  charset: 'utf8',
  logLevel: 'error',
  metafile: true,
  external: ['react'],
  alias: { 'react-dom': REACT_DOM_SHIM },
  define: { 'process.env.NODE_ENV': '"production"' },
}

const BLOCKED_SPEC =
  /^(?:node:|fs|path|os|crypto|child_process|net|tls|http|https|stream|worker_threads|serialport|modbus-serial|@serialport\/)/

function forbidNodeImports() {
  return {
    name: 'forbid-node-imports',
    setup(build) {
      build.onResolve({ filter: BLOCKED_SPEC }, (args) => {
        throw new Error(`client bundle must not import ${args.path} (from ${args.importer || 'entry'})`)
      })
    },
  }
}

function shouldStickToBottom(scrollTop, scrollHeight, clientHeight, threshold = 5) {
  return scrollHeight - scrollTop - clientHeight <= threshold
}

function validateVirtualCompat() {
  const makeEl = (h = 300) => ({
    scrollTop: 0,
    scrollHeight: 0,
    offsetHeight: h,
    offsetWidth: 300,
    getBoundingClientRect() {
      return { width: 300, height: h }
    },
    addEventListener() {},
    removeEventListener() {},
  })
  const win = {
    ResizeObserver: class {
      observe() {}
      unobserve() {}
    },
    requestAnimationFrame: (cb) => setTimeout(cb, 0),
    cancelAnimationFrame: () => {},
  }
  const sample = (count) => {
    const el = makeEl(300)
    const v = new Virtualizer({
      count,
      getScrollElement: () => el,
      estimateSize: () => 36,
      overscan: 5,
      scrollToFn: () => {},
      observeElementRect: (_, cb) => {
        cb({ width: 300, height: 300 })
        return () => {}
      },
      observeElementOffset: (_, cb) => {
        cb(0, false)
        return () => {}
      },
    })
    v.scrollElement = el
    v.targetWindow = win
    v.scrollRect = { width: 300, height: 300 }
    v.scrollOffset = 0
    v.measurementsCache = Array.from({ length: count }, (_, i) => ({
      index: i,
      start: i * 36,
      size: 36,
      end: (i + 1) * 36,
      key: i,
    }))
    void v.measureElement
    return v.getVirtualItems()
  }
  const a = sample(500)
  const b = sample(1000)
  const c = sample(5000)
  if (a.length >= 50 || b.length >= 50 || c.length >= 50) throw new Error('Virtualizer DOM should be viewport-limited')
  if (Math.abs(a.length - b.length) > 5 || Math.abs(b.length - c.length) > 5)
    throw new Error('500/1000/5000 should have similar viewport DOM count')
  if (!shouldStickToBottom(700, 1000, 300) || shouldStickToBottom(0, 1000, 300))
    throw new Error('autoFollow shouldStickToBottom only at bottom')
}
validateVirtualCompat()

function asNamedIife(name, raw) {
  let text = String(raw || '').trim()
  text = text.replace(/^['"]use strict['"];/, '').trim()
  text = text.replace(/;+$/, '')
  const decl = new RegExp('^var\\s+' + name + '\\s*=\\s*')
  const rhs = decl.test(text) ? text.replace(decl, '') : text
  return 'var ' + name + ' = ' + rhs + ';'
}

function readUplotCss() {
  const p = join(root, 'node_modules/uplot/dist/uPlot.min.css')
  try {
    return readFileSync(p, 'utf8')
  } catch (error) {
    throw new Error('无法读取 uPlot 官方 CSS: ' + p + ' (' + error.message + ')')
  }
}

async function buildNamedBundle(name, entry) {
  const result = await esbuild.build({
    ...ESBUILD_COMMON,
    entryPoints: [entry],
    globalName: name,
    plugins: [forbidNodeImports()],
  })
  const js = asNamedIife(name, result.outputFiles[0].text)
  return { js, metafile: result.metafile, bytes: Buffer.byteLength(js, 'utf8') }
}

function wrapModuleLoader(vendorJs, vendorCss, clientJs) {
  // Vendor CSS is injected as DvbVendorCss. Dark mode uses plugin CSS vars /
  // prefers-color-scheme, not a second chart global.
  return (
    BANNER +
    `window.__ModuleLoader__.load({
  id: 'dsh-vision-bench',
  factory(require) {
    ${vendorJs}
    var DvbVendorCss = ${JSON.stringify('\n' + vendorCss.trim())};
    ${clientJs}
    return {
      name: 'dsh-vision-bench',
      inject: ['slots'],
      apply: DvbClient.apply,
    }
  },
})
`
  )
}

export { normalizeNewlines, sha256Text }

export function pluginBodyOf(src) {
  const text = normalizeNewlines(src)
  const marker = '\nvar DvbVendorCss = '
  const i = text.indexOf(marker)
  if (i < 0) return text
  const cssStart = i + marker.length
  const afterCss = text.indexOf('\n', cssStart)
  return text.slice(afterCss < 0 ? cssStart : afterCss)
}

export async function buildClientSource() {
  const vendor = await buildNamedBundle('DvbVendor', 'scripts/vendor-entry.mjs')
  const client = await buildNamedBundle('DvbClient', 'src/ui/client/client-entry.mjs')
  const source = wrapModuleLoader(vendor.js, readUplotCss(), client.js)
  const bytes = Buffer.byteLength(source, 'utf8')
  assertClientBudget({
    bytes,
    source,
    vendorMetafile: vendor.metafile,
    clientMetafile: client.metafile,
  })
  return {
    source,
    bytes,
    hash: sha256Text(source),
    vendorBytes: vendor.bytes,
    clientBytes: client.bytes,
    vendorMetafile: vendor.metafile,
    clientMetafile: client.metafile,
  }
}

async function main() {
  const first = await buildClientSource()
  const second = await buildClientSource()
  if (first.hash !== second.hash) {
    throw new Error('client build is not deterministic: ' + first.hash + ' vs ' + second.hash)
  }
  const dest = join(root, 'client.js')
  const check = process.argv.includes('--check')
  if (check) {
    const current = readFileSync(dest, 'utf8')
    const currentHash = sha256Text(current)
    if (currentHash !== first.hash) {
      console.error('client.js is stale; run node scripts/build-client.mjs')
      console.error(`disk ${currentHash} vs generated ${first.hash} (${first.bytes} bytes)`)
      process.exit(1)
    }
    process.exit(0)
  }
  writeFileSync(dest, first.source)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error) => {
    console.error('build-client failed:', error && error.message ? error.message : error)
    process.exit(1)
  })
}
